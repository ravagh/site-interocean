/**
 * vite-plugin-site — build-time HTML composition for a static multipage site.
 *
 * Directives (HTML comments, so source files stay valid HTML):
 *
 *   <!-- @include header active="about" -->
 *       Inlines partials/header.html. Attributes become {{placeholders}}.
 *       In the header, the link with data-nav="<active>" gets aria-current="page".
 *
 *   <!-- @logo variant="primary|negative" class="…" -->
 *       Official logo: /assets/logos/logo-<variant>.svg if present, else .png,
 *       else a typographic "INTER OCEAN" fallback. Intrinsic size is read from
 *       the file so the header never shifts.
 *
 *   <!-- @picture name="category-energy-solar" alt="…" sizes="…" class="…"
 *                 loading="lazy|eager" fetchpriority="high" -->
 *       Responsive <picture> (AVIF + WebP srcset) from public/assets/images/manifest.json
 *       (generated by `npm run images`). Missing images render a branded placeholder.
 *
 *   <!-- @icon btn-arrow -->   (also: arrow, arrow-up-right, arrow-down, mail, pin)
 *       Inline SVG icons; decorative (aria-hidden).
 *
 *   <!-- @hero-media -->
 *       Hero media container. Only media files that actually exist are referenced
 *       (video, mobile video, webm, frame sequence); the poster is always rendered.
 *
 * Also replaces {{siteUrl}} everywhere and emits sitemap.xml + robots.txt on build.
 */
import { readFileSync, existsSync } from 'node:fs';
import { resolve, join } from 'node:path';

const ATTR_RE = /([\w-]+)="([^"]*)"/g;
const DIRECTIVE_RE = /<!--\s*@(include|logo|picture|hero-media|icon)\b([^]*?)-->/g;

const SVG_ATTRS = 'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"';
const ICONS = {
  arrow: `<svg ${SVG_ATTRS}><path d="M5 12h14M13 6l6 6-6 6"/></svg>`,
  'arrow-up-right': `<svg ${SVG_ATTRS}><path d="M7 17 17 7M8 7h9v9"/></svg>`,
  'arrow-down': `<svg ${SVG_ATTRS}><path d="M12 5v14M6 13l6 6 6-6"/></svg>`,
  mail: `<svg ${SVG_ATTRS}><rect x="3" y="5" width="18" height="14" rx="2"/><path d="m4 7 8 6 8-6"/></svg>`,
  pin: `<svg ${SVG_ATTRS}><path d="M12 21s-7-6.2-7-11.5a7 7 0 0 1 14 0C19 14.8 12 21 12 21z"/><circle cx="12" cy="9.5" r="2.5"/></svg>`,
};
// Button icon: two stacked arrows for the hover "loop" animation.
ICONS['btn-arrow'] = `<span class="btn__icon" aria-hidden="true">${ICONS.arrow}${ICONS.arrow}</span>`;

function parseAttrs(str = '') {
  const attrs = {};
  for (const [, key, value] of str.matchAll(ATTR_RE)) attrs[key] = value;
  return attrs;
}

const escapeAttr = (s = '') => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

/** Reads intrinsic dimensions of a PNG (IHDR) or SVG (width/height or viewBox). */
function imageSize(file) {
  try {
    if (file.endsWith('.png')) {
      const buf = readFileSync(file);
      return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
    }
    if (file.endsWith('.svg')) {
      const svg = readFileSync(file, 'utf8').slice(0, 4000);
      const vb = svg.match(/viewBox="[\d.\s-]*?([\d.]+)\s+([\d.]+)"/);
      if (vb) return { width: Math.round(+vb[1]), height: Math.round(+vb[2]) };
      const w = svg.match(/\swidth="([\d.]+)/);
      const h = svg.match(/\sheight="([\d.]+)/);
      if (w && h) return { width: Math.round(+w[1]), height: Math.round(+h[1]) };
    }
  } catch { /* fall through */ }
  return null;
}

export default function sitePlugin(options = {}) {
  let root = process.cwd();
  const siteUrl = (options.siteUrl || 'https://www.interoceanco.com').replace(/\/$/, '');
  const pages = options.pages || [];

  const publicPath = (p) => join(root, 'public', p);
  const readManifest = () => {
    const file = publicPath('assets/images/manifest.json');
    return existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : {};
  };

  function renderLogo({ variant = 'primary', class: cls = '', alt = 'Inter Ocean' }) {
    for (const ext of ['svg', 'png', 'webp']) {
      const rel = `assets/logos/logo-${variant}.${ext}`;
      if (!existsSync(publicPath(rel))) continue;
      const size = imageSize(publicPath(rel)) || { width: 1000, height: 164 };
      return `<img class="${escapeAttr(cls)}" src="/${rel}" width="${size.width}" height="${size.height}" alt="${escapeAttr(alt)}" decoding="async">`;
    }
    // Typographic fallback — used only until official files are provided.
    return `<span class="${escapeAttr(cls)} brand-wordmark brand-wordmark--${variant}" role="img" aria-label="${escapeAttr(alt)}"><span>INTER</span> <span>OCEAN</span></span>`;
  }

  function renderPicture(attrs, manifest) {
    const { name, alt = '', sizes = '100vw', class: cls = '', loading = 'lazy', fetchpriority, media } = attrs;
    const img = manifest[name];
    const altAttr = `alt="${escapeAttr(alt)}"`;
    if (!img) {
      // Missing asset: branded placeholder that keeps the layout intact.
      return `<div class="media media--placeholder ${escapeAttr(cls)}" role="${alt ? 'img' : 'presentation'}" ${alt ? `aria-label="${escapeAttr(alt)}"` : ''} data-missing-image="${escapeAttr(name)}"></div>`;
    }
    const srcset = (ext) => img.widths.map((w) => `/assets/images/${name}-${w}.${ext} ${w}w`).join(', ');
    const fallbackW = img.widths.find((w) => w >= 1024) || img.widths[img.widths.length - 1];
    const style = `--media-color:${img.color};background-image:url(${img.lqip})`;
    const extra = media ? ` media="${media}"` : '';
    return [
      `<picture class="media ${escapeAttr(cls)}" style="${style}">`,
      `<source type="image/avif" srcset="${srcset('avif')}" sizes="${escapeAttr(sizes)}"${extra}>`,
      `<source type="image/webp" srcset="${srcset('webp')}" sizes="${escapeAttr(sizes)}"${extra}>`,
      `<img src="/assets/images/${name}-${fallbackW}.webp" width="${img.width}" height="${img.height}" ${altAttr} loading="${loading}" decoding="${loading === 'eager' ? 'sync' : 'async'}"${fetchpriority ? ` fetchpriority="${fetchpriority}"` : ''}>`,
      `</picture>`,
    ].join('');
  }

  function renderHeroMedia(manifest) {
    const has = (p) => existsSync(publicPath(p));
    const data = [];
    if (has('assets/videos/hero-scroll.mp4')) data.push('data-video="/assets/videos/hero-scroll.mp4"');
    if (has('assets/videos/hero-scroll-mobile.mp4')) data.push('data-video-mobile="/assets/videos/hero-scroll-mobile.mp4"');
    if (has('assets/videos/hero-scroll.webm')) data.push('data-video-webm="/assets/videos/hero-scroll.webm"');
    if (has('assets/frames/hero/manifest.json')) data.push('data-frames="/assets/frames/hero/manifest.json"');

    const poster = manifest['hero-poster'];
    const posterMobile = manifest['hero-poster-mobile'];
    let posterHtml = '';
    if (poster) {
      const set = (n, ext) => manifest[n].widths.map((w) => `/assets/images/${n}-${w}.${ext} ${w}w`).join(', ');
      posterHtml = [
        `<picture class="hero-media__poster" style="background-color:${poster.color}">`,
        posterMobile ? `<source type="image/avif" media="(max-aspect-ratio: 4/5)" srcset="${set('hero-poster-mobile', 'avif')}" sizes="100vw">` : '',
        posterMobile ? `<source type="image/webp" media="(max-aspect-ratio: 4/5)" srcset="${set('hero-poster-mobile', 'webp')}" sizes="100vw">` : '',
        `<source type="image/avif" srcset="${set('hero-poster', 'avif')}" sizes="100vw">`,
        `<source type="image/webp" srcset="${set('hero-poster', 'webp')}" sizes="100vw">`,
        `<img src="/assets/images/hero-poster.webp" width="${poster.width}" height="${poster.height}" alt="" fetchpriority="high" decoding="async">`,
        `</picture>`,
      ].join('');
      data.push(`data-poster="/assets/images/hero-poster.webp"`);
    } else {
      posterHtml = `<div class="hero-media__poster hero-media__poster--fallback"></div>`;
    }
    return `<div class="hero-media" data-hero-media ${data.join(' ')}>${posterHtml}</div>`;
  }

  function compose(html, depth = 0) {
    if (depth > 5) return html;
    const manifest = readManifest();
    return html.replace(DIRECTIVE_RE, (_, type, rawAttrs) => {
      const attrs = parseAttrs(rawAttrs);
      if (type === 'logo') return renderLogo(attrs);
      if (type === 'icon') return ICONS[rawAttrs.trim().split(/\s+/)[0]] || '';
      if (type === 'picture') return renderPicture(attrs, manifest);
      if (type === 'hero-media') return renderHeroMedia(manifest);
      // include
      const name = rawAttrs.trim().split(/\s+/)[0];
      const file = join(root, 'partials', `${name}.html`);
      if (!existsSync(file)) return `<!-- partial "${name}" not found -->`;
      let partial = readFileSync(file, 'utf8');
      partial = partial.replace(/\{\{(\w+)\}\}/g, (m, key) => (key in attrs ? escapeAttr(attrs[key]) : m));
      if (attrs.active) {
        partial = partial.replace(new RegExp(`data-nav="${attrs.active}"`, 'g'), `data-nav="${attrs.active}" aria-current="page"`);
      }
      return compose(partial, depth + 1);
    });
  }

  return {
    name: 'inter-ocean-site',
    configResolved(config) {
      root = config.root;
    },
    configureServer(server) {
      // Reload the browser when partials, logos, media or the image manifest change.
      const watched = [join(root, 'partials'), publicPath('assets')];
      server.watcher.add(watched);
      server.watcher.on('change', (file) => {
        if (watched.some((dir) => resolve(file).startsWith(resolve(dir)))) server.ws.send({ type: 'full-reload' });
      });
      server.watcher.on('add', (file) => {
        if (resolve(file).startsWith(resolve(publicPath('assets')))) server.ws.send({ type: 'full-reload' });
      });
    },
    transformIndexHtml: {
      order: 'pre',
      handler(html) {
        return compose(html).replace(/\{\{siteUrl\}\}/g, siteUrl);
      },
    },
    generateBundle() {
      if (!pages.length) return;
      const today = new Date().toISOString().slice(0, 10);
      const urls = pages
        .filter((p) => !p.noindex)
        .map((p) => `  <url>\n    <loc>${siteUrl}${p.path}</loc>\n    <lastmod>${today}</lastmod>\n    <priority>${p.priority ?? 0.8}</priority>\n  </url>`)
        .join('\n');
      this.emitFile({
        type: 'asset',
        fileName: 'sitemap.xml',
        source: `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`,
      });
      this.emitFile({
        type: 'asset',
        fileName: 'robots.txt',
        source: `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}/sitemap.xml\n`,
      });
    },
  };
}

